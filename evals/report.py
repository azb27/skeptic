"""Build docs/results/bench.md from stored runs (no API calls).

python -m evals.report
"""

from __future__ import annotations

import datetime as dt
import json

import numpy as np

from evals.rules_baseline import MANIFEST
from skeptic import config
from skeptic.stats import mcnemar_exact

OUT = config.ROOT / "docs" / "results" / "bench.md"
OUT_JSON = config.ROOT / "docs" / "results" / "bench_summary.json"
RUNS = config.RUNS_DIR / "evals"
LABELS = {
    "rules": "Rules only (checks, fixed thresholds, no LLM)",
    "sonnet_full": "Sonnet 5 auditor: code + checks",
    "haiku_full": "Haiku 4.5 auditor: code + checks",
    "sonnet_nocode": "Sonnet 5, checks only (no code access)",
    "sonnet_nochecks": "Sonnet 5, code only (no checks)",
}
GROUPS = ["survives", "leak", "multiple_testing", "costs", "no_edge"]
GROUP_NAMES = {"survives": "Real edge, clean code (SURVIVES)", "leak": "Look-ahead leaks", "multiple_testing": "Multiple testing",
               "costs": "Killed by costs", "no_edge": "No edge, clean code"}  # fmt: skip


def load(name: str) -> dict[str, dict]:
    p = RUNS / name / "results.jsonl"
    return (
        {json.loads(line)["id"]: json.loads(line) for line in p.read_text().splitlines()}
        if p.exists()
        else {}
    )


def strat_ci(
    ok: np.ndarray, strata: np.ndarray, n_boot: int = 10_000, seed: int = 27
) -> tuple[float, float, float]:
    rng = np.random.default_rng(seed)
    groups = [np.flatnonzero(strata == s) for s in np.unique(strata)]
    draws = np.empty(n_boot)
    for b in range(n_boot):
        idx = np.concatenate([rng.choice(g, len(g)) for g in groups])
        draws[b] = ok[idx].mean()
    lo, hi = np.quantile(draws, [0.025, 0.975])
    return float(ok.mean()), float(lo), float(hi)


def pct(t) -> str:
    return f"**{100 * t[0]:.0f}%** [{100 * t[1]:.0f}, {100 * t[2]:.0f}]"


def main() -> None:
    manifest = {e["id"]: e for e in json.loads(MANIFEST.read_text())}
    ids = sorted(manifest)
    runs = {n: load(n) for n in LABELS}
    runs = {n: r for n, r in runs.items() if len(r) == len(ids)}
    group = np.array([manifest[i]["group"] for i in ids])
    leak_ids = [i for i in ids if manifest[i]["group"] == "leak"]
    probe_missed = {i for i in leak_ids if manifest[i]["oracle"].get("future_blind") == "PASS"}

    summ = {}
    for n, r in runs.items():
        ok = np.array([r[i]["score"]["verdict_ok"] for i in ids], dtype=float)
        coarse = np.array(
            [r[i]["score"]["coarse_ok"] and r[i]["score"]["verdict_ok"] for i in ids], dtype=float
        )
        surv = group == "survives"
        rej = ~surv
        s = {
            "acc": strat_ci(ok, group),
            "false_reject": float(1 - ok[surv].mean()),
            "miss": float(1 - ok[rej].mean()),
            "reason": strat_ci(coarse, group),
            "fine_leak": float(np.mean([r[i]["score"]["fine_ok"] for i in leak_ids])),
            "located": float(np.mean([bool(r[i]["score"]["located"]) for i in leak_ids])),
            "probe_missed_caught": [r[i]["score"]["verdict_ok"] for i in sorted(probe_missed)],
            "probe_missed_located": [bool(r[i]["score"]["located"]) for i in sorted(probe_missed)],
            "cost_per_case": float(np.mean([r[i].get("cost_usd", 0.0) for i in ids])),
            "total_cost": float(np.sum([r[i].get("cost_usd", 0.0) for i in ids])),
            "p50": float(np.median([r[i].get("latency_s", 0.0) for i in ids])),
            "by_group": {g: float(ok[group == g].mean()) for g in GROUPS},
        }
        summ[n] = s

    L = [
        "# Skeptic bench: results",
        "",
        "Generated by `python -m evals.report` from `runs/evals/*/results.jsonl` (produced by `python -m evals.rules_baseline` "
        "and `python -m evals.run_agent --config <name>`). Do not edit by hand.",
        "",
        f"*Built {dt.datetime.now():%Y-%m-%d %H:%M}. Bench: {len(ids)} cases from `python -m bench.build` (seed 2027); "
        "ground truth in `bench/manifest.json`.*",
        "",
        "## Headline",
        "Share of cases with the correct verdict, and with the correct verdict *for the right reason* (coarse flaw class: "
        "leak, multiple testing, costs, no edge, none). 95% bootstrap intervals, resampled within each group.",
        "",
        "| Configuration | Verdict correct | Right reason | False rejects (of 30 real edges) | Misses (of 60 flaws) | Leak class exact | Leak line found (±3) | $ / case | Median time |",
        "|---|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for n, s in summ.items():
        L.append(
            f"| {LABELS[n]} | {pct(s['acc'])} | {pct(s['reason'])} | {s['false_reject'] * 30:.0f} | {s['miss'] * 60:.0f} | "
            f"{100 * s['fine_leak']:.0f}% | {100 * s['located']:.0f}% | ${s['cost_per_case']:.3f} | {s['p50']:.0f}s |"
        )
    L += ["", "## By group (verdict correct)", "", "| Group | n | " + " | ".join(LABELS[n] for n in summ) + " |",
          "|---|---:|" + "---:|" * len(summ)]  # fmt: skip
    for g in GROUPS:
        L.append(
            f"| {GROUP_NAMES[g]} | {int((group == g).sum())} | "
            + " | ".join(f"{100 * s['by_group'][g]:.0f}%" for s in summ.values())
            + " |"
        )

    L += ["", f"## The leaks the truncation probe could not see ({len(probe_missed)} of {len(leak_ids)})",
          "`future_blind` passed these cases, so the only way to reject them for the right reason is to read the code.", "",
          "| Configuration | Rejected | Leak line found |", "|---|---:|---:|"]  # fmt: skip
    for n, s in summ.items():
        c, loc = s["probe_missed_caught"], s["probe_missed_located"]
        L.append(f"| {LABELS[n]} | {sum(c)}/{len(c)} | {sum(loc)}/{len(loc)} |")

    if "sonnet_full" in runs:
        L += ["", "## Are the differences real?", "Exact McNemar test on verdicts, same cases.", "",
              "| A vs B | Only A right | Only B right | p |", "|---|---:|---:|---:|"]  # fmt: skip
        a = runs["sonnet_full"]
        for n in summ:
            if n == "sonnet_full":
                continue
            b_ = runs[n]
            only_a = sum(a[i]["score"]["verdict_ok"] and not b_[i]["score"]["verdict_ok"] for i in ids)
            only_b = sum(b_[i]["score"]["verdict_ok"] and not a[i]["score"]["verdict_ok"] for i in ids)
            L.append(
                f"| Sonnet full vs {LABELS[n]} | {only_a} | {only_b} | {mcnemar_exact(only_a, only_b):.3g} |"
            )

        L += [
            "",
            "## Every wrong verdict: Sonnet 5 auditor",
            "",
            "| Case | Group | Truth | Verdict | Class given | Summary (start) |",
            "|---|---|---|---|---|---|",
        ]
        for i in ids:
            r = a[i]
            if not r["score"]["verdict_ok"]:
                v = r["verdict"]
                L.append(f"| {i} | {manifest[i]['group']} / {manifest[i]['flaw']} | {manifest[i]['truth']} | {v.get('verdict')} | "
                         f"{v.get('flaw_class')} | {(v.get('summary') or '').replace('|', '/')[:220]} |")  # fmt: skip

    L += ["", "## How to read this",
          "- **Ground truth is by construction.** Markets are synthetic; edges and flaws are planted. An oracle confirms "
          "every real-edge, no-edge, cost and multiple-testing case (`bench/build.py`); leak cases are leaks by "
          "construction, whatever the probe says.",
          "- **The rules-only baseline sees the same check results** as the agents (shared cache), so differences come from "
          "reading code and notes, not from different numbers.",
          "- **Leaks on null markets** are also caught by the backtest (no real edge), so a verdict can be right for the wrong "
          "reason. The *right reason* column and the leak-line column separate those.",
          "- **One run per configuration.** Model sampling varies between runs; small differences are inside the intervals.",
          "- **The bench measures the planted classes only.** A pass here says nothing about flaws outside them.",
          "- Bench corrections found while running it are logged in [`evals/CORRECTIONS.md`](../../evals/CORRECTIONS.md)."]  # fmt: skip
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    OUT_JSON.write_text(json.dumps(summ, indent=1, default=float) + "\n")
    print(f"wrote {OUT}")
    for n, s in summ.items():
        print(
            f"{n:16s} acc {100 * s['acc'][0]:.0f}%  reason {100 * s['reason'][0]:.0f}%  located {100 * s['located']:.0f}%  ${s['total_cost']:.2f}"
        )


if __name__ == "__main__":
    main()
