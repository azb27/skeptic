"""Render docs/case-study-gold-sniper.md from docs/results/case_study_gold_sniper.json (no API calls).

    python -m evals.case_study

The JSON holds aggregates only. It was produced by private scripts that run Aziz's harness, which is not
published. The original write-ups are in case_study/.
"""

from __future__ import annotations

import json

from skeptic import config

SRC = config.ROOT / "docs" / "results" / "case_study_gold_sniper.json"
OUT = config.ROOT / "docs" / "case-study-gold-sniper.md"


def ci(x) -> str:
    m, lo, hi = x
    return f"{m:+.3f}R [{lo:+.3f}, {hi:+.3f}]"


def main() -> None:
    d = json.loads(SRC.read_text())
    r, c, ag = d["replay"], d["checks"], d["agent"]
    a5, f5, h1 = r["5m_2024-09_2026-01"], r["5m_2020_2026"], r["1h_2020_2026"]
    L = [
        "# Case study: auditing my own XAUUSD system",
        "",
        "Generated by `python -m evals.case_study` from `docs/results/case_study_gold_sniper.json`. The harness runs that "
        "produced the JSON use private code; the JSON holds aggregates only. Do not edit by hand.",
        "",
        "## What was being audited",
        "Gold Sniper v5.3 is a rule-based intraday XAUUSD system I wrote in Pine: ICC phases, fair-value gaps, killzones and "
        "multi-timeframe bias, with 1:1 targets. In September 2026 I pre-registered three hypotheses to improve it "
        "([`case_study/PREREGISTRATION.md`](../case_study/PREREGISTRATION.md)) and ran them through a Python re-implementation "
        "of the script ([`case_study/RESULTS.md`](../case_study/RESULTS.md)). In the published copies the broker's name is "
        'replaced with "broker"; nothing else was changed.',
        "",
        "That run found **+0.007R per trade before spread and −0.123R at a $0.50 spread** over 2,092 trades on a commercial "
        "spot feed. All three hypotheses failed their locked promotion rules, and the system was frozen. The run's own fidelity "
        "gate was **unmet**, so those numbers were formally provisional.",
        "",
        "## 1. Independent replay on a third feed",
        f"Same harness, a different price source: {d['feed']}. Cross-asset scoring was off because the container can't reach "
        "the data vendor. It is capped at ±0.75 on the score, so it can only move signals near the threshold.",
        "",
        "| Run | Trades | Hit TP1 | Gross (no spread) | Net @ $0.20 | Net @ $0.50 | Net @ $0.90 | Median stop |",
        "|---|---:|---:|---|---|---|---|---:|",
    ]
    for name, row in (("5-min, Sep 2024 – Jan 2026 (overlaps the original run)", a5),
                      ("5-min, 2020 – Jan 2026", f5), ("1-hour port, 2020 – Jan 2026", h1)):  # fmt: skip
        L.append(f"| {name} | {row['trades']:,} | {100 * row['tp1_rate']:.1f}% | {ci(row['net_0.00'])} | {ci(row['net_0.20'])} | "
                 f"{ci(row['net_0.50'])} | {ci(row['net_0.90'])} | ${row['median_stop_usd']:.2f} |")  # fmt: skip
    L += [
        "",
        "95% intervals resample whole trading days. Ambiguous bars (stop and target both touched) are counted as stops.",
        "",
        f"- **The original result reproduces.** On the overlapping period the hit rate is {100 * a5['tp1_rate']:.1f}% "
        f"(original 49.67%), and net at $0.50 is {a5['net_0.50'][0]:+.3f}R (original −0.123R). The gross edge "
        f"({a5['net_0.00'][0]:+.3f}R) is again indistinguishable from zero. Three feeds now agree: the original commercial "
        "spot feed, COMEX futures, and this one.",
        f"- **Over six years it is worse.** Stops were smaller in 2020–2023, so the same dollar spread costs more in R: "
        f"{f5['net_0.50'][0]:+.3f}R per trade at $0.50.",
        f"- **The hourly port loses less, but still has no edge.** Gross {h1['net_0.00'][0]:+.3f}R. At $0.50 the interval "
        f"just touches zero ({ci(h1['net_0.50'])}); at $0.90 it is clearly negative.",
        f"- **Two independent engines agree.** Skeptic's bracket engine replayed the harness's signals with its own exit logic "
        f"and matched the harness's TP1 outcome on {100 * a5['engine_agreement_tp1']:.1f}% (5-min) and "
        f"{100 * h1['engine_agreement_tp1']:.1f}% (1-hour) of trades.",
        "",
        "## 2. Skeptic's checks on the harness",
        "The harness itself was the strategy: Skeptic called it on truncated and full data, and replayed its signals.",
        "",
        "| Check | Result | Evidence |",
        "|---|---|---|",
    ]
    ev = {
        "future_blind": f"{c['future_blind']['evidence']['cut_points']} cut points (including 25 at the system's own signal bars), no decision changed",
        "backtest": f"net {c['backtest']['evidence']['mean']:+.4f}R per trade, CI {c['backtest']['evidence']['ci95']}, {c['backtest']['evidence']['trades']:,} trades",
        "costs": f"gross {c['costs']['evidence']['gross_mean']:+.4f}R; break-even spread ${c['costs']['evidence']['breakeven_spread_usd']:.2f} vs $0.50",
        "random_entry": f"actual {c['random_entry']['evidence']['actual_mean']:+.4f}R vs random entries with the same stops and timeout {c['random_entry']['evidence']['random_mean']:+.4f}R (p = {c['random_entry']['evidence']['p_value']:.2f})",
        "stability": f"{c['stability']['evidence']['losing_folds']} of {len(c['stability']['evidence']['folds'])} time folds lose money",
    }  # fmt: skip
    for k in ("future_blind", "backtest", "costs", "random_entry", "stability"):
        L.append(f"| `{k}` | {c[k]['result']} | {ev[k]} |")
    L += [
        "",
        '- **No look-ahead found.** The first run of the probe did flag the harness, but each "mismatch" was a trade on the final '
        "bar that the harness drops because it can't be resolved. That is censoring, not look-ahead; the check was fixed and "
        "the fix logged ([`evals/CORRECTIONS.md`](../evals/CORRECTIONS.md) #2).",
        "- **The entries add nothing measurable.** Random entries with the same stops and timeout do about as well. Whatever "
        "the rules are detecting, it doesn't survive the exits and the spread.",
        "",
        "## 3. The auditor's verdict",
        f"Sonnet 5 (effort high) read the write-ups and harness, ran the checks, and returned **{ag['verdict']['verdict']}**, "
        f"class `{ag['verdict']['flaw_class']}`, for ${ag['cost_usd']:.2f}:",
        "",
        f"> {ag['verdict']['summary']}",
        "",
        "## 4. What the auditor missed (my own review of the process)",
        "The auditor judged the research process sound. Reading the two documents against each other, I found three things it "
        "should have raised. None changes the conclusion, but an auditor that only confirms the authors is not doing its job:",
        "",
        "1. **Out-of-sample discipline isn't recorded.** The pre-registration says the most recent 30% is \"not examined until "
        "an IS decision is recorded in this file's changelog\". The changelog has one entry (the lock), and RESULTS.md reports "
        "in-sample and out-of-sample side by side. It didn't matter here, because every hypothesis already failed in-sample, "
        "but the rule as written was not followed.",
        "2. **The fidelity gate failed on more than one count.** The gate needs ADX within 0.5 mean absolute error; the "
        "harness README reports 0.74 on futures. The results file mentions only the signal-count shortfall (18 of 25 vs ≥ 23).",
        "3. **Two live-trade counts.** The pre-registration cites 25 live trades; the harness README says all 29 live trades "
        "were reproduced. Both can be true at different dates, but the record should say which sample the gate was judged on.",
        "",
        "This is exactly the failure mode the bench's planned *write-up only* group targets (SPEC §5): research documents that "
        "break their own rules. On this case the auditor read the conclusions, not the rules.",
        "",
        "## Bottom line",
        "Three feeds, two engines and Skeptic's checks agree. **Gold Sniper v5.3 has no directional edge at this horizon and "
        "target geometry; the spread is the whole loss.** The original decision to freeze it stands. What's worth keeping is "
        "the process: pre-registration, a stopping rule, clustered uncertainty, and an independent re-run that confirms it.",
    ]
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
