"""Rerun the API auditor several times on chosen cases: is a wrong verdict stable, or sampling noise?

    python -m evals.repeat --ids case_28,case_42,case_74 --n 3      # ~$0.25; writes docs/results/repeats.md

Same configuration as the bench's `sonnet_full` run (prompt, tools, caps, cached check numbers). The cases
are chosen because they failed, so the output is per case, never a rate.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
from concurrent.futures import ThreadPoolExecutor

from evals.rules_baseline import CASES, MANIFEST
from evals.run_agent import check_runner
from evals.scoring import score
from skeptic import config
from skeptic.agent.loop import Auditor
from skeptic.agent.tools import CaseTools

OUT = config.ROOT / "docs" / "results" / "repeats.md"
RUN_DIR = config.RUNS_DIR / "repeats"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ids", required=True)
    ap.add_argument("--n", type=int, default=3)
    a = ap.parse_args()
    manifest = {c["id"]: c for c in json.loads(MANIFEST.read_text())}
    jobs = [(manifest[i], k) for i in a.ids.split(",") for k in range(a.n)]
    RUN_DIR.mkdir(parents=True, exist_ok=True)

    def one(job: tuple[dict, int]) -> dict:
        case, k = job
        tools = CaseTools(CASES / case["id"], check_runner(case))
        res = Auditor(model=config.MODEL, config_name="repeat").audit(case["id"], tools, trace_dir=RUN_DIR)
        v = res.verdict or {"verdict": "", "flaw_class": "none"}
        return {"id": case["id"], "k": k, "truth": case["truth"], "verdict": v, "ok": score(case, v)["verdict_ok"],
                "cost_usd": res.cost_usd}  # fmt: skip

    with ThreadPoolExecutor(max_workers=4) as ex:
        rows = list(ex.map(one, jobs))
    (RUN_DIR / "results.jsonl").write_text("".join(json.dumps(r, default=str) + "\n" for r in rows))
    L = ["# Repeated audits of chosen cases", "",
         f"Generated by `python -m evals.repeat --ids {a.ids} --n {a.n}` on {dt.date.today()}, model `{config.MODEL}`, "
         "same configuration as the bench's `sonnet_full` run. Cases chosen because they failed: per case, not a rate.",
         "", "| Case | Truth | Verdicts across runs (flaw class) | Correct | $ |", "|---|---|---|---:|---:|"]  # fmt: skip
    for i in a.ids.split(","):
        rs = [r for r in rows if r["id"] == i]
        verdicts = ", ".join(f"{r['verdict'].get('verdict')} ({r['verdict'].get('flaw_class')})" for r in rs)
        L.append(f"| {i} | {rs[0]['truth']} | {verdicts} | {sum(r['ok'] for r in rs)}/{len(rs)} | "
                 f"{sum(r['cost_usd'] for r in rs):.3f} |")  # fmt: skip
    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
